// Package docgen generates the rule reference in docs/rules from the rule
// catalog: an index and one page per rule. Output is deterministic so that
// regenerating unchanged rules produces no diff.
package docgen

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/Voskan/codexsentinel/v2/analyzer/catalog"
)

// categoryNames orders and names the categories in the index.
var categoryNames = []struct{ id, name string }{
	{catalog.CategorySecurity, "Security"},
	{catalog.CategoryReliability, "Reliability & Concurrency"},
	{catalog.CategorySupplyChain, "Supply Chain & Provenance"},
	{catalog.CategoryArchitecture, "Architecture"},
	{catalog.CategoryLicense, "License"},
	{catalog.CategoryMetrics, "Code Metrics"},
	{catalog.CategorySuppression, "Suppression Policy"},
	{catalog.CategoryStyle, "Style"},
	{catalog.CategoryCorrectness, "Correctness"},
}

func categoryName(id string) string {
	for _, c := range categoryNames {
		if c.id == id {
			return c.name
		}
	}
	return id
}

// Files returns the generated files, keyed by file name.
func Files() map[string][]byte {
	docs := catalog.All()
	files := map[string][]byte{"README.md": index(docs)}
	for _, d := range docs {
		files[d.ID+".md"] = page(d)
	}
	return files
}

// Write generates the reference into dir, replacing generated pages and
// removing pages of rules that no longer exist.
func Write(dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	files := Files()
	existing, err := filepath.Glob(filepath.Join(dir, "*.md"))
	if err != nil {
		return err
	}
	for _, path := range existing {
		if _, ok := files[filepath.Base(path)]; !ok {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	for name, data := range files {
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func index(docs []catalog.RuleDoc) []byte {
	byCategory := map[string][]catalog.RuleDoc{}
	for _, d := range docs {
		byCategory[d.Category] = append(byCategory[d.Category], d)
	}
	var b bytes.Buffer
	b.WriteString("<!-- Generated by go run ./cmd/docgen -out docs/rules. Do not edit. -->\n\n")
	b.WriteString("# CodexSentinel Rules\n\n")
	fmt.Fprintf(&b, "CodexSentinel reports %d rules. Each page explains what a rule detects, why it matters in Go, a problematic and a safe example, and how to configure or suppress it. `codex-cli explain <rule>` prints the same information.\n\n", len(docs))
	b.WriteString("| Category | Rules |\n| --- | ---: |\n")
	for _, c := range categoryNames {
		if n := len(byCategory[c.id]); n > 0 {
			fmt.Fprintf(&b, "| [%s](#%s) | %d |\n", c.name, anchor(c.name), n)
		}
	}
	for _, c := range categoryNames {
		list := byCategory[c.id]
		if len(list) == 0 {
			continue
		}
		sort.Slice(list, func(i, j int) bool { return list[i].Code < list[j].Code })
		fmt.Fprintf(&b, "\n## %s\n\n", c.name)
		b.WriteString("| Code | Rule ID | Severity | CWE / OWASP | Auto-Fix | Summary |\n| --- | --- | --- | --- | --- | --- |\n")
		for _, d := range list {
			fmt.Fprintf(&b, "| %s | [`%s`](%s.md) | %s | %s | %s | %s |\n",
				d.Code, d.ID, d.ID, d.DefaultSeverity, classification(d), yesNo(d.HasAutoFix), cell(d.Summary))
		}
	}
	return b.Bytes()
}

func page(d catalog.RuleDoc) []byte {
	var b bytes.Buffer
	b.WriteString("<!-- Generated by go run ./cmd/docgen -out docs/rules. Do not edit. -->\n\n")
	fmt.Fprintf(&b, "# [%s] %s (%s)\n\n", d.Code, d.Title, d.ID)
	fmt.Fprintf(&b, "%s\n\n", d.Summary)
	b.WriteString("| | |\n| --- | --- |\n")
	fmt.Fprintf(&b, "| **Severity** | %s |\n", d.DefaultSeverity)
	fmt.Fprintf(&b, "| **Category** | %s |\n", categoryName(d.Category))
	fmt.Fprintf(&b, "| **CWE** | %s |\n", linkCWE(d.CWE))
	fmt.Fprintf(&b, "| **OWASP** | %s |\n", dash(d.OWASP))
	fmt.Fprintf(&b, "| **Auto-Fix supported** | %s |\n\n", yesNo(d.HasAutoFix))
	fmt.Fprintf(&b, "## Why It Matters in Go\n\n%s\n\n", d.Explanation)
	fence := "go"
	if d.ExampleLang != "" {
		fence = "text"
	}
	fmt.Fprintf(&b, "## Vulnerable / Problematic Example\n\n```%s\n%s\n```\n\n", fence, strings.TrimRight(d.BadExample, "\n"))
	fmt.Fprintf(&b, "## Safe / Idiomatic Go Pattern\n\n```%s\n%s\n```\n\n", fence, strings.TrimRight(d.GoodExample, "\n"))
	b.WriteString("## Configuration & Suppression\n\n")
	fmt.Fprintf(&b, "Disable the rule for the whole module in `.codexsentinel.yaml`:\n\n```yaml\nrules:\n  disabled: [%s]\n```\n\n", d.ID)
	fmt.Fprintf(&b, "Change its severity:\n\n```yaml\nrules:\n  severity_overrides:\n    %s: low\n```\n\n", d.ID)
	fmt.Fprintf(&b, "Suppress one reviewed finding on its line, with the reason:\n\n```go\n//codex:ignore %s -- <reason>\n```\n\n", d.ID)
	fmt.Fprintf(&b, "Or ignore it under a path in `.codexsentinel.ignore`:\n\n```text\ninternal/legacy/** %s\n```\n\n", d.ID)
	if len(d.References) > 0 {
		b.WriteString("## References\n\n")
		for _, r := range d.References {
			fmt.Fprintf(&b, "- <%s>\n", r)
		}
		b.WriteString("\n")
	}
	b.WriteString("[All rules](README.md)\n")
	return b.Bytes()
}

func classification(d catalog.RuleDoc) string {
	var parts []string
	for _, p := range []string{d.CWE, d.OWASP} {
		if p != "" {
			parts = append(parts, p)
		}
	}
	if len(parts) == 0 {
		return "-"
	}
	return strings.Join(parts, " / ")
}

func linkCWE(cwe string) string {
	n, ok := strings.CutPrefix(cwe, "CWE-")
	if !ok {
		return dash(cwe)
	}
	return fmt.Sprintf("[%s](https://cwe.mitre.org/data/definitions/%s.html)", cwe, n)
}

func yesNo(b bool) string {
	if b {
		return "Yes"
	}
	return "No"
}

func dash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// anchor returns the GitHub heading anchor of a heading text.
func anchor(heading string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(heading) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '-':
			b.WriteRune(r)
		case r == ' ':
			b.WriteByte('-')
		}
	}
	return b.String()
}
