package formats

import (
	"fmt"
	"strings"
	"time"

	"github.com/Voskan/codexsentinel/v2/report"
)

// WriteMarkdownReport generates a markdown report from the given issues and writes it to the provided path.
func WriteMarkdownReport(issues []report.Issue, outPath string, gitMeta *report.GitMetadata) error {
	summary := report.ComputeSummary(issues)

	content := generateMarkdownContent(issues, summary, gitMeta)

	return writeOutput(outPath, []byte(content))
}

// generateMarkdownContent creates the markdown content
func generateMarkdownContent(issues []report.Issue, summary report.Summary, gitMeta *report.GitMetadata) string {
	var b strings.Builder
	b.WriteString("# 🔒 CodexSentinel Security Report\n\n")
	fmt.Fprintf(&b, "**Generated:** %s\n\n", time.Now().Format(time.RFC3339))
	writeGitSection(&b, gitMeta)
	writeSummarySection(&b, summary)
	if len(issues) == 0 {
		b.WriteString("## ✅ No Issues Found\n\n")
		b.WriteString("No issues were reported for the analyzed code.\n\n")
	} else {
		writeIssueTables(&b, issues)
		writeIssueDetails(&b, issues)
	}
	writeRecommendations(&b, summary)
	b.WriteString("---\n\n")
	b.WriteString("*Generated by CodexSentinel — https://github.com/Voskan/codexsentinel*\n")
	return b.String()
}

func writeGitSection(b *strings.Builder, gitMeta *report.GitMetadata) {
	if gitMeta == nil || gitMeta.RepoRoot == "" {
		return
	}
	b.WriteString("## 📁 Repository Information\n\n")
	b.WriteString("| Property | Value |\n|----------|-------|\n")
	fmt.Fprintf(b, "| Repository | `%s` |\n", gitMeta.RepoRoot)
	rows := []struct {
		name, value string
		show        bool
	}{
		{"Branch", "`" + gitMeta.Branch + "`", gitMeta.Branch != ""},
		{"Commit", fmt.Sprintf("`%s` (%s)", gitMeta.CommitShort, gitMeta.CommitHash), gitMeta.CommitHash != ""},
		{"Author", fmt.Sprintf("%s <%s>", gitMeta.Author, gitMeta.Email), gitMeta.Author != ""},
		{"Message", gitMeta.Message, gitMeta.Message != ""},
		{"Date", gitMeta.Timestamp.Format("2006-01-02 15:04:05"), !gitMeta.Timestamp.IsZero()},
		{"Status", "⚠️ Working directory has uncommitted changes", gitMeta.IsDirty},
	}
	for _, row := range rows {
		if row.show {
			fmt.Fprintf(b, "| %s | %s |\n", row.name, row.value)
		}
	}
	b.WriteString("\n")
}

// severitySections lists the severities in report order with their headings.
var severitySections = []struct {
	level report.SeverityLevel
	label string
}{
	{report.SeverityCritical, "🔴 Critical"},
	{report.SeverityHigh, "🟠 High"},
	{report.SeverityMedium, "🟡 Medium"},
	{report.SeverityLow, "🟢 Low"},
	{report.SeverityInfo, "🔵 Info"},
}

func severityCount(summary report.Summary, level report.SeverityLevel) int {
	switch level {
	case report.SeverityCritical:
		return summary.Critical
	case report.SeverityHigh:
		return summary.High
	case report.SeverityMedium:
		return summary.Medium
	case report.SeverityLow:
		return summary.Low
	}
	return summary.Info
}

func writeSummarySection(b *strings.Builder, summary report.Summary) {
	b.WriteString("## 📊 Summary\n\n")
	b.WriteString("| Severity | Count | Percentage |\n|----------|-------|------------|\n")
	for _, sec := range severitySections {
		count, pct := severityCount(summary, sec.level), 0.0
		if summary.Total > 0 {
			pct = float64(count) / float64(summary.Total) * 100
		}
		fmt.Fprintf(b, "| %s | %d | %.1f%% |\n", sec.label, count, pct)
	}
	fmt.Fprintf(b, "| **Total** | **%d** | **100.0%%** |\n\n", summary.Total)
	b.WriteString("| Category | Count |\n|----------|-------|\n")
	fmt.Fprintf(b, "| 🔒 Security | %d |\n| 🛡️ Reliability | %d |\n| 🏗️ Architecture | %d |\n| 📦 Supply chain | %d |\n| 🎨 Style | %d |\n| ✔️ Correctness | %d |\n| 📊 Metrics | %d |\n| 📄 License | %d |\n| 🚫 Suppression | %d |\n\n",
		summary.Security, summary.Reliability, summary.Architecture, summary.SupplyChain, summary.Style, summary.Correctness, summary.Metrics, summary.License, summary.Suppression)
}

func writeIssueTables(b *strings.Builder, issues []report.Issue) {
	b.WriteString("## 🚨 Issues by Severity\n\n")
	for _, sec := range severitySections {
		group := filterIssuesBySeverity(issues, strings.ToLower(string(sec.level)))
		if len(group) == 0 {
			continue
		}
		fmt.Fprintf(b, "### %s\n\n", sec.label)
		b.WriteString("| File | Line | Rule | Description |\n|------|------|------|-------------|\n")
		for _, issue := range group {
			fmt.Fprintf(b, "| `%s` | %d | `%s` | %s |\n", issue.File, issue.Line, issue.RuleID, tableCell(issue.Description))
		}
		b.WriteString("\n")
	}
}

func writeIssueDetails(b *strings.Builder, issues []report.Issue) {
	b.WriteString("## 📋 Issue Details\n\n")
	for i, issue := range issues {
		fmt.Fprintf(b, "### %d. %s\n\n", i+1, issue.Title)
		fmt.Fprintf(b, "**Severity:** %s\n\n", getSeverityBadge(string(issue.Severity)))
		fmt.Fprintf(b, "**File:** `%s:%d`\n\n", issue.File, issue.Line)
		fmt.Fprintf(b, "**Rule ID:** `%s`\n\n", issue.RuleID)
		if tags := classification(issue); tags != "" {
			fmt.Fprintf(b, "**Classification:** %s\n\n", tags)
		}
		fmt.Fprintf(b, "**Description:** %s\n\n", issue.Description)
		if len(issue.Trace) > 0 {
			b.WriteString("**Data flow:**\n\n")
			for _, line := range issue.TraceLines() {
				b.WriteString("    " + line + "\n")
			}
			b.WriteString("\n")
		}
		if issue.Suggestion != "" {
			fmt.Fprintf(b, "**💡 Suggestion:** %s\n\n", issue.Suggestion)
		}
		if issue.Fix != nil && len(issue.Fix.Edits) > 0 {
			b.WriteString("**Patch:**\n\n")
			for _, e := range issue.Fix.Edits {
				b.WriteString("    " + agentEdit(e, issue.File) + "\n")
			}
			b.WriteString("\n")
		}
		if issue.Reference != "" {
			fmt.Fprintf(b, "**📚 Reference:** [%s](%s)\n\n", issue.Reference, issue.Reference)
		}
		b.WriteString("---\n\n")
	}
}

func writeRecommendations(b *strings.Builder, summary report.Summary) {
	b.WriteString("## 💡 Recommendations\n\n")
	switch {
	case summary.Critical > 0 || summary.High > 0:
		b.WriteString("1. **Fix critical and high severity issues first** - they pose the highest risk\n")
		b.WriteString("2. **Add regression tests** for each fixed vulnerability\n")
		b.WriteString("3. **Record accepted findings** in a baseline (`codex-cli baseline create`) so new code is held to a clean standard\n\n")
	case summary.Medium > 0:
		b.WriteString("1. **Review medium severity issues** during regular maintenance\n")
		b.WriteString("2. **Run scans in pull requests** with `--diff` to keep new code clean\n\n")
	default:
		b.WriteString("1. **Keep scanning in CI** to catch regressions early\n")
		b.WriteString("2. **Keep dependencies current** and re-run the dependency audit regularly\n\n")
	}
}

// filterIssuesBySeverity filters issues by severity level
func filterIssuesBySeverity(issues []report.Issue, severity string) []report.Issue {
	var filtered []report.Issue
	for _, issue := range issues {
		if strings.ToLower(string(issue.Severity)) == severity {
			filtered = append(filtered, issue)
		}
	}
	return filtered
}

// getSeverityBadge returns a markdown badge for severity
func getSeverityBadge(severity string) string {
	switch strings.ToLower(severity) {
	case "critical":
		return "🔴 Critical"
	case "high":
		return "🟠 High"
	case "medium":
		return "🟡 Medium"
	case "low":
		return "🟢 Low"
	case "info":
		return "🔵 Info"
	default:
		return severity
	}
}

// classification lists the CWE, OWASP category, rule category and
// confidence of a finding.
func classification(issue report.Issue) string {
	var tags []string
	for _, tag := range []string{issue.CWE, owaspTag(issue.OWASP), issue.Category} {
		if tag != "" {
			tags = append(tags, tag)
		}
	}
	if issue.Confidence > 0 {
		tags = append(tags, fmt.Sprintf("confidence %.0f%%", issue.Confidence*100))
	}
	return strings.Join(tags, " · ")
}

func owaspTag(owasp string) string {
	if owasp == "" {
		return ""
	}
	return "OWASP " + owasp
}

// tableCell keeps text on one line and escapes the column separator.
func tableCell(s string) string {
	return strings.ReplaceAll(oneLine(s), "|", "\\|")
}
